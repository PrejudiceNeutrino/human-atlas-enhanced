import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { parseGallery } from '../app/learn/gallery/model.ts';
import { parsePracticeDataset, practiceForFigure } from '../app/learn/gallery/label-practice-model.ts';

const root = 'public/images/learn/digestive/gallery';
const gallery = parseGallery(JSON.parse(fs.readFileSync(`${root}/gallery.json`, 'utf8')));
const data = parsePracticeDataset(JSON.parse(fs.readFileSync(`${root}/label-practice.json`, 'utf8')), 'digestive', gallery);
assert.equal(data.figures.length, gallery.items.length, 'Every source figure needs a coverage decision.');
const rows = gallery.items.map(figure => {
  assert.equal(createHash('sha256').update(fs.readFileSync(`${root}/${figure.image}`)).digest('hex'), figure.sha256, `${figure.id}: source image changed`);
  const { entry, stale, labels } = practiceForFigure(data, figure);
  assert.ok(entry && !stale, `${figure.id}: missing or stale coverage review`);
  return { figure, entry, count: labels.length, regions: labels.reduce((sum, label) => sum + label.regions.length, 0) };
});
const count = predicate => rows.filter(predicate).length;
const summary = {
  totalFigures: rows.length,
  eligibleFigures: count(row => row.entry.reviewStatus !== 'not-applicable'),
  playableFigures: count(row => row.count > 0),
  completeFigures: count(row => row.entry.coverage === 'complete'),
  partialFigures: count(row => row.entry.coverage === 'partial'),
  candidates: count(row => row.entry.reviewStatus === 'candidate'),
  notApplicable: count(row => row.entry.reviewStatus === 'not-applicable'),
  verifiedLabels: rows.reduce((sum, row) => sum + row.count, 0),
  maskRegions: rows.reduce((sum, row) => sum + row.regions, 0),
};
const report = `# Digestive Gallery Label Practice coverage

Generated by \`npm run audit:label-practice -- --write\`. All 30 original source images were visually inspected; opaque-mask proofs were reviewed against the originals on November 6, 2026. The audit revalidates the schema, image hashes, and counts. It cannot replace visual mask review.

${Object.entries(summary).map(([key, value]) => `- ${key}: ${value}`).join('\n')}

"Complete" covers the eligible, identifiable printed structure/callout names, including repeated answer text where present. Figure titles, copyright lines, plastic model numbers, and unrelated explanatory prose are not quiz answers. Unreadable labels are excluded; identifiable edge-clipped terms in a05, a12, and a13 are covered to the image boundary following user review. "Partial" figures show a notice during practice; they are not presented as fully annotated. Verified means transcription and masking were visually reviewed against the source, not independent clinical certification.

| ID | Figure | Review | Coverage | Answers | Regions | Remaining work / review notes |
| --- | --- | --- | --- | ---: | ---: | --- |
${rows.map(({ figure, entry, count, regions }) => `| ${figure.id} | ${figure.title} | ${entry.reviewStatus} | ${entry.coverage} | ${count} | ${regions} | ${entry.reviewNotes.replaceAll('|', '/')} |`).join('\n')}

## Remaining work

- a07, p03, p08, p15 remain candidates with no published practice masks. Their repeated terms, cropped source text, or narrative layout need coordinated transcription and masking.
- a05, a12, a13 include the requested Sublingual Salivary Gland, Round Ligament, and Cystic Duct covers, including their identifiable text at the source boundaries. Original crops remain unchanged.
- p13 publishes four grouped answers. Gallbladder and sphincter process questions still need curation.
- a01 and p04 remain ordinary Gallery images because they contain no meaningful printed structure labels.
- No original image, thumbnail, manifest, source, or rights metadata was changed. This report and the annotation sidecar are separate metadata.
`;
const destination = 'docs/gallery-label-practice-coverage.md';
if (process.argv.includes('--write')) fs.writeFileSync(destination, report, 'utf8');
else assert.equal(fs.readFileSync(destination, 'utf8'), report, 'Coverage report is stale; run with --write.');
console.log(JSON.stringify(summary, null, 2));
